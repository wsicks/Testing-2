//   active        → endpoint verified reachable from this app (or already
//                   integrated as a venue adapter) and keyless
//   disabled      → free tier exists but requires an API key that is not
//                   configured; the note says which env var unlocks it
//   manual_review → no permitted structured API found (e.g. congressional
//                   financial disclosures ship as PDFs behind a search UI —
//                   we will NOT scrape them)
//   unavailable   → no permitted source exists for the category at all
//
// `lastTermsReview` is stamped when the registry is (re)seeded; the terms
// summary in allowedUse/prohibitedUse is a good-faith reading, not legal
// advice, and sources flip to manual_review when terms change.

