/** stamp seed-time review + neutral reliability into full records */
export function seedSourceRecords(now: number): SourceRecord[] {
  return SOURCE_SEEDS.map((s) => ({
    ...s,
    reliabilityScore: s.status === "active" ? 0.8 : 0.5,
    lastTermsReview: now,
  }));
}
